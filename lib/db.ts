// src/lib/db.ts

import { PrismaClient } from '@prisma/client'
import { PrismaMariaDb } from '@prisma/adapter-mariadb'

/**
 * =========================================================================
 * چرا این الگو (Singleton Pattern) انتخاب شده است؟
 * =========================================================================
 * در فریم‌ورک Next.js و در محیط توسعه (Development)، هر بار که فایلی را تغییر داده و ذخیره می‌کنید،
 * قابلیت Hot Reloading فایل‌ها را مجدداً اجرا می‌کند. اگر کلاینت Prisma را بدون این ساختار بسازیم،
 * با هر بار ذخیره کد، یک اتصال (Connection) جدید به دیتابیس MySQL باز می‌شود. خیلی زود تعداد این 
 * اتصال‌ها از حد مجاز دیتابیس فراتر رفته و MySQL خطای "Too many connections" می‌دهد که منجر به
 * از دسترس خارج شدن سرور و خطای ۵۰۰ می‌شود. 
 * این الگو تضمین می‌کند که در کل طول اجرای برنامه، فقط و فقط یک کلاینت فعال (Singleton) وجود دارد.
 * 
 * =========================================================================
 * چرا از @prisma/adapter-mariadb استفاده شده است؟
 * =========================================================================
 * در پریسما نسخه ۷ به بعد، موتورهای سنگین Rust که در پشت صحنه کار می‌کردند، حذف شده‌اند.
 * پریسما اکنون شما را ملزم می‌کند که از آداپتورهای بومی جاوااسکریپت استفاده کنید. برای اتصال به MySQL
 * و MariaDB، پکیج رسمی @prisma/adapter-mariadb بهینه‌ترین گزینه است زیرا با استفاده از درایور بومی
 * سیستم، سرعت و کارایی بالاتری نسبت به موتورهای قدیمی در محیط‌های بدون سرور (Serverless) ارائه می‌دهد.
 */

// ۱. این تابع به عنوان سازنده اصلی کلاینت عمل می‌کند.
// هر زمان که نیاز به ساخت یک کلاینت جدید باشد، این متد فراخوانی می‌شود.
const prismaClientSingleton = () => {
  // الف) ساخت آداپتور اتصال ماریا دی‌بی/MySQL با استفاده از آدرس دیتابیس موجود در متغیرهای محیطی
  const adapter = new PrismaMariaDb(process.env.DATABASE_URL!)
  
  // ب) ارسال آداپتور به سازنده PrismaClient تا ارتباط تحت کنترل این آداپتور انجام شود
  return new PrismaClient({ adapter })
}

// ۲. تعریف یک متغیر سراسری در سطح گلوبال با استفاده از قابلیت‌های تایپ‌اسکریپت.
// این کار مانع از آن می‌شود که کلاینت پریسما در بازسازی‌های مکرر Next.js دوباره از ابتدا ساخته شود.
declare global {
  var prismaGlobal: undefined | ReturnType<typeof prismaClientSingleton>
}

// ۳. بررسی وجود کلاینت قبلی در محیط گلوبال:
// اگر کلاینت از قبل در globalThis موجود باشد از همان استفاده می‌کند، در غیر این صورت تابع ساخت را اجرا می‌کند.
export const prisma = globalThis.prismaGlobal ?? prismaClientSingleton()

// ۴. در صورتی که در محیط توسعه (Production نباشد) باشیم، کلاینت ساخته شده را در محیط سراسری ذخیره می‌کنیم
// تا در بازخوانی‌های بعدی (Hot Reload) از همین وهله استفاده مجدد شود.
if (process.env.NODE_ENV !== 'production') globalThis.prismaGlobal = prisma